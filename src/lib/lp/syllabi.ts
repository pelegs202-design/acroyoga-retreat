/**
 * Audience-specific landing-page content for the 5 warm-lead LPs.
 *
 * Hebrew-only. No prices anywhere — the call closes on the phone.
 * Each variant maps to /he/lp/{slug} and the same content drives:
 *   - Hero (headline, lossSub, heroReel, hookLine)
 *   - Outcome bullets, testimonials, FAQs
 *   - 4-week syllabus (transformation arc, not curriculum)
 *   - WhatsApp pre-filled message (so Shay knows which LP they came from)
 *
 * Tone: warm leads — they already showed interest. Hit them with the
 * "this is exactly what I needed" feeling, not a brochure. Each LP has:
 *   - hookLine: the line they screenshot and send to a friend
 *   - weeks[].shift: the "this is the moment when..." emotional payoff per week
 */

import type { LpVariant } from "@/lib/quiz/quiz-analytics";

export type Slug = "fun" | "handstand" | "tribe" | "trust" | "control" | "dance";

export interface Bullet {
  title: string;
  desc: string;
}

export interface Testimonial {
  quote: string;
  name: string;
}

export interface Faq {
  q: string;
  a: string;
}

export interface SyllabusWeek {
  week: string;
  title: string;
  body: string;
  /** The "this is the moment when X clicks" payoff — the line that lands. */
  shift: string;
}

export interface Syllabus {
  variant: Extract<LpVariant, Slug>;
  /** Instagram reel shortcode used for hero background video. File at /public/reels/<reel>.mp4 */
  heroReel: string;
  /** Short overline above the headline */
  eyebrow: string;
  /** H1 — punchy, visceral */
  headline: string;
  /** The "screenshot and send to a friend" line under the H1 */
  hookLine: string;
  /** Sub-headline that twists the knife */
  lossSub: string;
  /** Pre-filled WhatsApp message body sent to Shay — high-intent tone */
  waMessage: string;
  /** Section heading for the 3 outcome bullets */
  outcomesTitle: string;
  outcomes: [Bullet, Bullet, Bullet];
  /** Section heading for syllabus */
  syllabusTitle: string;
  syllabusSub: string;
  weeks: [SyllabusWeek, SyllabusWeek, SyllabusWeek, SyllabusWeek];
  testimonials: [Testimonial, Testimonial, Testimonial];
  faqs: Faq[];
  /** Final CTA banner */
  finalTitle: string;
  finalSub: string;
}

